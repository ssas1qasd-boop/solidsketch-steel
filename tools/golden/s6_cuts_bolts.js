// S6 golden: Tekla bolt groups (v58 stBolts, every option) and cut parts through the live v69 chain, and R10 regenerated.
//   node tools/golden/s6_cuts_bolts.js        -> tests/steel/golden/s6/bolts.json (small), r10_regen.json (large: owner bundle)
'use strict';
const fs = require('fs');
const path = require('path');
const { GOLDEN, REPO, openV69, openSS } = require('./lib/v69');

// TKBOLT groups as R10 stores them: pts (head side), ax, d, grip, plus the v58 Tekla options in q.
const B = (q) => Object.assign({ pts: [[0, 0, 0], [0, 80, 0], [0, 0, 70], [0, 80, 70]], ax: [1, 0, 0], d: 20, grip: 30, grade: '8.8' }, q);
const BOLTS = {
  std_m20: B({}),
  m16_tol: B({ d: 16, tol: 1 }),
  m30: B({ d: 30, grip: 50 }),
  holes_only: B({ holesOnly: 1 }),
  anchor: B({ anchor: 1, d: 24, grip: 300 }),
  skip_second: B({ skip: [1] }),
  bdel_2_3: B({ bdel: '2 3' }),
  stag_1: B({ stag: 1, pts: [[0, 0, 0], [0, 80, 0], [0, 160, 0], [0, 0, 70], [0, 80, 70], [0, 160, 70]] }),
  stag_2: B({ stag: 2, pts: [[0, 0, 0], [0, 80, 0], [0, 160, 0], [0, 0, 70], [0, 80, 70], [0, 160, 70]] }),
  stag_3: B({ stag: 3, pts: [[0, 0, 0], [0, 80, 0], [0, 160, 0], [0, 0, 70], [0, 80, 70], [0, 160, 70]] }),
  stag_4: B({ stag: 4, pts: [[0, 0, 0], [0, 80, 0], [0, 160, 0], [0, 0, 70], [0, 80, 70], [0, 160, 70]] }),
  bdir_2: B({ bdir: 2 }),
  blen_15: B({ blen: 15 }),
  slotted: B({ htype: 'Slotted', sl1: 0, sl2: 20 }),
  slotted_rot: B({ htype: 'Slotted', sl1: 12, sl2: 0, srot: 1 }),
  oversized: B({ htype: 'Oversized', sl2: 6 }),
  tapped: B({ htype: 'Tapped' }),
  no_hole: B({ htype: 'No hole' }),
  no_washer_nut: B({ ba_w: 0, ba_n: 0 }),
  no_bolt: B({ ba_b: 0 }),
  skewed_axis: B({ ax: [0.6, 0, 0.8], pts: [[0, 0, 0], [0, 90, 0]] }),
  vertical_axis: B({ ax: [0, 0, -1], pts: [[0, 0, 0], [100, 0, 0], [0, 100, 0], [100, 100, 0]] }),
};
const CUTS = {
  cut_box: { cut: { prof: 'PL40*120', p1: [-10, 0, 7450], p2: [300, 0, 7450] } },
  cut_tube: { cut: { prof: 'CHS88.9*5', p1: [0, -200, 7300], p2: [0, 200, 7300], rot: 'Front' } },
};

(async () => {
  const R = v => Math.round(v * 100) / 100;
  const { browser, page } = await openV69({ log: false });
  let small, big;
  try {
    small = await page.evaluate(({ bolts, cuts, Rs }) => {
      const R = new Function('v', Rs);
      const info = m => { if (!m) return null; const bb = m.boundingBox(); return { volume: R(Math.abs(m.volume())), bbox: [...Array.from(bb.min), ...Array.from(bb.max)].map(R) }; };
      const out = {};
      for (const [k, q] of Object.entries(bolts)) {
        try {
          const g = __st.live.connGeom({ id: 9000, type: 'TKBOLT', parts: [1, 2], q });
          if (!g) { out[k] = { q, geom: null }; continue; }
          const cut1 = g.cuts.get(1), cut2 = g.cuts.get(2); const part = g.parts[0];
          out[k] = { q, holes1: cut1 ? cut1.map(info) : null, holes2: cut2 ? cut2.map(info) : null, part: part ? Object.assign({ name: part.name }, info(part.man), { bolts: part.bolts }) : null };
        } catch (e) { out[k] = { q, error: String(e.message || e) }; }
      }
      for (const [k, q] of Object.entries(cuts)) {
        const g = __st.live.connGeom({ id: 9001, type: 'TKCUT', parts: [5], q });
        out[k] = { q, cut: g ? g.cuts.get(5).map(info) : null };
      }
      return out;
    }, { bolts: BOLTS, cuts: CUTS, Rs: 'return Math.round(v * 100) / 100' });

    // R10 regenerated by v69: every part rebuilt from its st and cut by its connections, every bolt group remade.
    await openSS(page, path.join(REPO, 'tests', 'steel', 'models', 'Frame_28x53m_R10.ss'));
    big = await page.evaluate(({ Rs }) => {
      const R = new Function('v', Rs); const S = __ss.S;
      const info = m => { const bb = m.boundingBox(); return [R(Math.abs(m.volume())), ...[...Array.from(bb.min), ...Array.from(bb.max)].map(R)]; };
      const t0 = performance.now();
      const ids = S.bodies.filter(b => b.st && (b.st.kind === 'member' || b.st.kind === 'plate')).map(b => b.id);
      __st.regen(ids);
      const ms = performance.now() - t0;
      const parts = {}, bolts = [];
      for (const b of S.bodies) {
        if (!b.st || !b.man) continue;
        if (b.st.kind === 'member' || b.st.kind === 'plate') parts[b.id] = info(b.man);
        else if (b.st.kind === 'bolts') bolts.push([b.st.conn, ...info(b.man)]);
      }
      const conns = S.stConns.reduce((a, c) => (a[c.type] = (a[c.type] || 0) + 1, a), {});
      return { ms: Math.round(ms), conns, nParts: Object.keys(parts).length, nBolts: bolts.length, parts, bolts };
    }, { Rs: 'return Math.round(v * 100) / 100' });
  } finally { await browser.close(); }
  const dir = path.join(GOLDEN, 's6'); fs.mkdirSync(dir, { recursive: true });
  const lines = Object.entries(small).map(([k, v]) => JSON.stringify(k) + ':' + JSON.stringify(v));
  fs.writeFileSync(path.join(dir, 'bolts.json'), '{"source":"web v69 __st.live.connGeom (TKBOLT through the v58 stBolts; TKCUT), volumes and boxes rounded to 0.01",\n"cases":{\n' + lines.join(',\n') + '\n}}\n');
  fs.writeFileSync(path.join(dir, 'r10_regen.json'), JSON.stringify({ source: 'web v69 __st.regen(every member and plate of R10): [volume, bbox min xyz, bbox max xyz] per part id; bolts: [conn, volume, bbox]', conns: big.conns, nParts: big.nParts, nBolts: big.nBolts, parts: big.parts, bolts: big.bolts }) + '\n');
  const errs = Object.entries(small).filter(([, v]) => v.error);
  console.log(`bolt/cut cases ${lines.length} (${errs.length} errors${errs.length ? ': ' + errs.map(([k, v]) => k + ' ' + v.error).join('; ') : ''}); R10 regen ${big.ms} ms: ${big.nParts} parts, ${big.nBolts} bolt groups, conns ${JSON.stringify(big.conns)}`);
})().catch(e => { console.error(e); process.exit(1); });
